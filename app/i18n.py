def tr(lang: str | None, key: str, **kwargs) -> str:
    table = TRANSLATIONS.get(lang or DEFAULT_LANG) or TRANSLATIONS[DEFAULT_LANG]
    text = table.get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except (KeyError, IndexError):
            pass
    return text


def get_lang(user) -> str:
    lang = getattr(user, "lang", None)
    return lang if lang in SUPPORTED_LANGS else DEFAULT_LANG
